import { readFileSync, writeFileSync } from 'node:fs';
import { buildSeed, type Raw } from '../src/lib/seed-build';

const raw = JSON.parse(readFileSync('data/raw.json', 'utf8')) as Raw;
const { words, categories, stats } = buildSeed(raw);

// 1) bundled JSON – the app works from this with no database at all
writeFileSync('src/data/seed.json', JSON.stringify({ words, categories }));

// 2) SQL for Supabase (run after supabase/migrations/0001_init.sql)
const q = (s: string | number | null) => (s === null ? 'null' : typeof s === 'number' ? String(s) : `'${s.replace(/'/g, "''")}'`);
const lines: string[] = ['-- generated by scripts/build-seed.ts – do not edit by hand', 'begin;'];
categories.forEach((c, i) => lines.push(`insert into public.categories (id, name, grp, sort_order) values (${q(c.id)}, ${q(c.name)}, ${q(c.group)}, ${i}) on conflict (id) do nothing;`));
for (const w of words) {
  lines.push(`insert into public.words (id, hebrew, translit, arabic, category_id, source, staged) values (${q(w.id)}, ${q(w.hebrew)}, ${q(w.translit)}, ${q(w.arabic)}, ${q(w.categoryId)}, 'seed', false) on conflict (id) do nothing;`);
}
for (const w of words) {
  for (const s of w.sentences) {
    lines.push(`insert into public.sentences (word_id, text, target, lesson) select ${q(w.id)}, ${q(s.text)}, ${q(s.target)}, ${q(s.lesson ?? null)} where not exists (select 1 from public.sentences x where x.word_id = ${q(w.id)} and x.text = ${q(s.text)});`);
  }
}
lines.push('commit;');
writeFileSync('supabase/seed.sql', lines.join('\n') + '\n');

console.log({ ...stats, review: undefined });
if (stats.review.length) console.log('low-confidence merges (worth a glance):\n' + stats.review.join('\n'));
